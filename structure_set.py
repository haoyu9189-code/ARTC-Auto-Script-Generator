def apply_rotation_matrix(point):
    """
    对点应用90度绕Z轴旋转矩阵
    R = [ 0   1   0 ]
        [-1   0   0 ]
        [ 0   0   1 ]

    Args:
        point: [x, y, z] 坐标列表

    Returns:
        [x', y', z'] 旋转后的坐标
    """
    x, y, z = point
    # 应用旋转矩阵: x' = 0*x + 1*y + 0*z = y
    #              y' = -1*x + 0*y + 0*z = -x
    #              z' = 0*x + 0*y + 1*z = z
    return [y, -x, z]


